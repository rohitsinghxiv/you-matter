// Applies the basic SEO setup: meta tags in index.html, robots.txt, sitemap.xml.
// Usage (from the project root):   node scripts/apply-seo.mjs https://your-domain.com
// Safe to re-run: it replaces its own block instead of duplicating it.
import { readFileSync, writeFileSync, mkdirSync, existsSync } from 'node:fs';

const arg = process.argv[2];
if (!arg || !/^https:\/\/[a-z0-9.-]+(:\d+)?$/i.test(arg.replace(/\/$/, ''))) {
  console.error('Usage: node scripts/apply-seo.mjs https://your-domain.com');
  process.exit(1);
}
const SITE = arg.replace(/\/$/, '');
const TITLE = 'You Matter: A Safe Space to Write, Share and Feel Heard';
const DESC =
  'A free peer-support journaling space. Write privately or share, receive kind words from others, try gentle coping exercises, and find crisis helplines by country.';
const SHORT = 'Write privately or share, receive kind words, and find help near you.';

const block = `<!-- SEO:START (generated by scripts/apply-seo.mjs) -->
    <title>${TITLE}</title>
    <meta name="description" content="${DESC}" />
    <link rel="canonical" href="${SITE}/" />
    <meta name="theme-color" content="#f8f3f0" />
    <meta property="og:site_name" content="You Matter" />
    <meta property="og:title" content="${TITLE}" />
    <meta property="og:description" content="${SHORT}" />
    <meta property="og:type" content="website" />
    <meta property="og:url" content="${SITE}/" />
    <meta property="og:image" content="${SITE}/og-image.png" />
    <meta property="og:image:width" content="1200" />
    <meta property="og:image:height" content="630" />
    <meta name="twitter:card" content="summary_large_image" />
    <meta name="twitter:title" content="${TITLE}" />
    <meta name="twitter:description" content="${SHORT}" />
    <meta name="twitter:image" content="${SITE}/og-image.png" />
    <script type="application/ld+json">
    ${JSON.stringify({ '@context': 'https://schema.org', '@type': 'WebSite', name: 'You Matter', url: `${SITE}/`, description: DESC })}
    </script>
    <!-- SEO:END -->`;

let html = readFileSync('index.html', 'utf8');
if (html.includes('<!-- SEO:START')) {
  html = html.replace(/<!-- SEO:START[\s\S]*?<!-- SEO:END -->/, block);
} else {
  // remove the tags we are about to replace, then insert the block after the viewport tag
  html = html
    .replace(/^\s*<title>[\s\S]*?<\/title>\s*\n/m, '')
    .replace(/^\s*<meta name="description"[^>]*>\s*\n/m, '')
    .replace(/^\s*<meta property="og:[^>]*>\s*\n/gm, '')
    .replace(/^\s*<meta name="twitter:[^>]*>\s*\n/gm, '');
  const viewport = html.match(/<meta name="viewport"[^>]*>/);
  if (!viewport) { console.error('Could not find the viewport meta tag in index.html'); process.exit(1); }
  html = html.replace(viewport[0], `${viewport[0]}\n    ${block}`);
}
writeFileSync('index.html', html);

mkdirSync('public', { recursive: true });
writeFileSync('public/robots.txt', `User-agent: *\nAllow: /\nDisallow: /api/\n\nSitemap: ${SITE}/sitemap.xml\n`);
const today = new Date().toISOString().slice(0, 10);
writeFileSync(
  'public/sitemap.xml',
  `<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n  <url>\n    <loc>${SITE}/</loc>\n    <lastmod>${today}</lastmod>\n  </url>\n</urlset>\n`
);

console.log(`SEO applied for ${SITE}`);
console.log('  updated   index.html (title, description, canonical, Open Graph, Twitter, JSON-LD)');
console.log('  wrote     public/robots.txt');
console.log('  wrote     public/sitemap.xml');
if (!existsSync('public/og-image.png')) {
  console.log('\nMISSING: public/og-image.png (1200x630). Link previews will have no image until you add it.');
}
console.log('\nNext: commit and push, then add the site in Google Search Console and submit', `${SITE}/sitemap.xml`);